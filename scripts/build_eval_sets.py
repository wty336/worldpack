def _dump(data: dict) -> str:
    """统一 YAML 渲染（确定性：固定字段顺序 + allow_unicode + 结尾换行）。"""
    return yaml.safe_dump(data, allow_unicode=True, sort_keys=False, default_flow_style=False, width=1000)


def build_dedup_pairs() -> dict:
    pairs: list[dict] = []
    for genre, sid, fact_a, paraphrases, contrasts in DEDUP_SEEDS:
        for i, b in enumerate(paraphrases, 1):
            pairs.append({
                "id": f"{sid}-syn{i}", "genre": genre, "kind": "同义改写",
                "expect_duplicate": True, "a": fact_a, "b": b,
            })
        for i, (b, kind) in enumerate(contrasts, 1):
            pairs.append({
                "id": f"{sid}-neg{i}", "genre": genre, "kind": kind,
                "expect_duplicate": False, "a": fact_a, "b": b,
            })
    for genre, cid, a, b, expect, kind in DEDUP_EDGE_CASES:
        pairs.append({
            "id": cid, "genre": genre, "kind": kind, "expect_duplicate": expect, "a": a, "b": b,
        })
    return {
        "version": 1,
        "generated_by": "scripts/build_eval_sets.py",
        "note": "正例=应拦截（同义改写）；负例=应放行（近义不同/边界）；历史 10 组保留以衔接旧数字",
        "pairs": pairs,
    }


def build_extract_cases() -> dict:
    cases = []
    for genre, cid, kind, existing, turn, recall, not_output, imp in EXTRACT_CASES:
        cases.append({
            "id": cid, "genre": genre, "axis_kind": kind,
            "expect_empty": kind == "负例",
            "existing": existing, "turn": turn,
            "must_recall": recall, "must_not_output": not_output,
            "importance_range": list(imp),
        })
    return {
        "version": 1,
        "generated_by": "scripts/build_eval_sets.py",
        "note": "must_recall=关键实体须被抽出的事实覆盖；must_not_output=已有事实不得重复输出；"
                "expect_empty=true 表示该回合无长期事实，应输出「无」(parse_facts → 空列表)",
        "cases": cases,
    }


TARGETS = {
    "dedup/pairs.yaml": build_dedup_pairs,
    "extract/direct.yaml": build_extract_cases,
}

# 冻结指纹只覆盖**纯评测产物**（本生成器的产物）。
# 世界包内的 judge_corpus.yaml 不在此列：它是"内容层资产"、会随作者迭代而变，
# 其口径由训练/评测报告里的 eval_set_sha256 记录，而不是用测试锁死。
DIGEST_FILE = "digests.json"


def write_digests() -> dict:
    import hashlib
    import json

    files = {}
    for rel in TARGETS:
        path = EVAL_DIR / rel
        rel_from_root = path.relative_to(REPO_ROOT).as_posix()
        files[rel_from_root] = hashlib.sha256(path.read_bytes()).hexdigest()
    payload = {
        "version": 1,
        "note": "由 scripts/build_eval_sets.py --digests 生成；改评测集须重跑生成器并同步本文件",
        "files": files,
    }
    (EVAL_DIR / DIGEST_FILE).write_text(
        json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return payload


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Phase 1 评测集生成器（确定性渲染）")
    parser.add_argument("--check", action="store_true", help="只校验磁盘文件与种子一致")
    parser.add_argument("--digests", action="store_true", help="生成后一并刷新 eval-sets/digests.json")
    args = parser.parse_args(argv)

    stale: list[str] = []
    for rel, builder in TARGETS.items():
        path = EVAL_DIR / rel
        rendered = _dump(builder())
        if args.check:
            on_disk = path.read_text(encoding="utf-8") if path.exists() else ""
            status = "一致" if on_disk == rendered else "**不一致**"
            if on_disk != rendered:
                stale.append(rel)
            print(f"  [{status}] {rel}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(rendered, encoding="utf-8")
            print(f"  [已写入] {rel}（{len(rendered.splitlines())} 行）")

    if args.digests:
        payload = write_digests()
        print(f"  [指纹] {DIGEST_FILE} 已刷新（{len(payload['files'])} 个文件）")

    if args.check and stale:
        print(f"\n[✗] {len(stale)} 个文件与生成器不一致——若是有意修改，请重跑生成器并更新 MANIFEST/digests")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
